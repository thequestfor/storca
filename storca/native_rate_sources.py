"""Bounded, read-only ancestry extraction for a retained native RMG model.

Database Python files are data here: they are parsed with AST, never imported,
executed, or evaluated.  Native annotations are checked against the retained
annotated Chemkin export.  A resolved source record is not a verified physical
rate, an electronic-state assignment, or an independently validated citation.
"""

import ast
import hashlib
import json
import math
import re
from pathlib import Path


POLICY_ID = "native-retained-rate-source-ancestry-v1"
MAX_FILE_BYTES = 8 * 1024 * 1024
MAX_AST_NODES = 300000
MAX_ENTRIES = 20000
MAX_MODEL_SPECIES = 32
MAX_MODEL_REACTIONS = 128
MAX_STRING_LENGTH = 200000
MAX_DEPTH = 24
_SAFE_CONSTRUCTORS = {
    "Arrhenius", "ArrheniusEP", "ArrheniusBM", "MultiArrhenius", "PDepArrhenius",
    "MultiPDepArrhenius", "Chebyshev", "ThirdBody", "Lindemann", "Troe",
    "RateUncertainty", "Article", "Book", "Thesis", "Reference", "ThermoData",
    "NASA", "NASAPolynomial", "Wilhoit", "RationalNumber",
}
_METADATA = {"name", "shortDesc", "longDesc", "reverse", "reversible", "autoGenerated",
             "reactantNum", "productNum", "boundaryAtoms", "solvent", "metal", "site", "facet"}


def _hash(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                     allow_nan=False).encode("utf-8")).hexdigest()


def _read(path):
    path = Path(path).resolve(strict=True)
    if not path.is_file() or path.stat().st_size > MAX_FILE_BYTES:
        raise ValueError("rate_source_file_missing_or_outside_size_policy")
    raw = path.read_bytes()
    if len(raw) > MAX_FILE_BYTES:
        raise ValueError("rate_source_file_outside_size_policy")
    return raw.decode("utf-8"), {"path": str(path), "sha256": hashlib.sha256(raw).hexdigest()}


def _reopen(record):
    if (not isinstance(record, dict) or set(record) != {"path", "sha256"}
            or not Path(record.get("path") or "").is_absolute()):
        raise ValueError("rate_source_artifact_invalid")
    text, actual = _read(record["path"])
    if actual != record:
        raise ValueError("rate_source_artifact_hash_mismatch")
    return text


def _literal(node, depth=0):
    if depth > MAX_DEPTH:
        raise ValueError("rate_source_expression_depth_exceeded")
    if isinstance(node, ast.Constant):
        value = node.value
        if not isinstance(value, (str, int, float, bool, type(None))):
            raise ValueError("rate_source_literal_unsupported")
        if isinstance(value, str) and len(value) > MAX_STRING_LENGTH:
            raise ValueError("rate_source_string_too_large")
        if isinstance(value, float) and not math.isfinite(value):
            raise ValueError("rate_source_literal_nonfinite")
        return value
    if isinstance(node, (ast.List, ast.Tuple)):
        return [_literal(item, depth + 1) for item in node.elts]
    if isinstance(node, ast.Dict):
        keys = [_literal(item, depth + 1) for item in node.keys]
        if any(not isinstance(key, str) for key in keys) or len(set(keys)) != len(keys):
            raise ValueError("rate_source_dictionary_keys_unsupported")
        return {key: _literal(value, depth + 1) for key, value in zip(keys, node.values)}
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
        value = _literal(node.operand, depth + 1)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError("rate_source_unary_expression_unsupported")
        return -value if isinstance(node.op, ast.USub) else value
    if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
            and node.func.id in _SAFE_CONSTRUCTORS):
        if any(keyword.arg is None for keyword in node.keywords):
            raise ValueError("rate_source_constructor_expansion_unsupported")
        names = [keyword.arg for keyword in node.keywords]
        if len(set(names)) != len(names):
            raise ValueError("rate_source_constructor_keyword_duplicate")
        return {"constructor": node.func.id,
                "args": [_literal(item, depth + 1) for item in node.args],
                "kwargs": {keyword.arg: _literal(keyword.value, depth + 1) for keyword in node.keywords}}
    raise ValueError("rate_source_expression_unsupported")


def parse_database_document(path, labels=None, indices=None):
    """Extract selected static records and their source header without execution.

    Unselected entry expressions are never interpreted; a bounded AST and
    strict top-level grammar still reject imports, loops, and arbitrary calls.
    Duplicate labels are allowed in a training depository, but selectors that
    match multiple records are explicitly unresolved by the ancestry builder.
    """
    text, artifact = _read(path)
    try:
        tree = ast.parse(text, filename=artifact["path"])
    except (SyntaxError, RecursionError, MemoryError) as error:
        raise ValueError("rate_source_database_ast_invalid") from error
    if sum(1 for _ in ast.walk(tree)) > MAX_AST_NODES:
        raise ValueError("rate_source_database_ast_too_large")
    metadata, entries, entry_count = {}, [], 0
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in _METADATA:
                if name in metadata:
                    raise ValueError("rate_source_database_metadata_duplicate")
                metadata[name] = _literal(node.value)
            elif name not in {"reverseMap", "reversibility", "forbidden", "reactantNum", "productNum"}:
                # Do not certify arbitrary executable Python as database data.
                _literal(node.value)
            continue
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            continue
        if not (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)
                and isinstance(node.value.func, ast.Name)
                and node.value.func.id in {"entry", "template", "recipe", "tree", "forbidden"}):
            raise ValueError("rate_source_database_top_level_unsupported")
        call = node.value
        if call.func.id != "entry":
            for argument in call.args:
                _literal(argument)
            for keyword in call.keywords:
                if keyword.arg is None:
                    raise ValueError("rate_source_database_expansion_unsupported")
                _literal(keyword.value)
            continue
        entry_count += 1
        if entry_count > MAX_ENTRIES or call.args or any(keyword.arg is None for keyword in call.keywords):
            raise ValueError("rate_source_database_entry_outside_policy")
        names = [keyword.arg for keyword in call.keywords]
        if len(set(names)) != len(names):
            raise ValueError("rate_source_database_entry_keyword_duplicate")
        fields = {keyword.arg: keyword.value for keyword in call.keywords}
        label, index = _literal(fields.get("label")), _literal(fields.get("index"))
        if not isinstance(label, str) or not label or isinstance(index, bool) or not isinstance(index, int):
            raise ValueError("rate_source_database_entry_identity_invalid")
        selected = ((labels is None and indices is None)
                    or (labels is not None and label in labels) or (indices is not None and index in indices))
        if selected:
            record = {name: _literal(value) for name, value in fields.items()}
            record["source_lines"] = {"start": node.lineno, "end": node.end_lineno}
            entries.append(record)
    return {"artifact": artifact, "parsed": {"metadata": metadata, "entries": entries,
                                             "entry_count_in_file": entry_count}}


def parse_species_dictionary(path, labels=None):
    text, artifact = _read(path)
    species, seen = [], set()
    for raw_block in re.split(r"\n\s*\n", text.strip()):
        lines = [line.strip() for line in raw_block.splitlines() if line.strip() and not line.lstrip().startswith("//")]
        if not lines:
            continue
        label = lines[0]
        if len(lines) < 2 or label in seen or len(seen) >= MAX_ENTRIES:
            raise ValueError("rate_source_dictionary_identity_invalid_or_duplicate")
        seen.add(label)
        if labels is not None and label not in labels:
            continue
        declarations = [line for line in lines[1:] if line.startswith("multiplicity")]
        if len(declarations) > 1 or (declarations and not re.fullmatch(r"multiplicity [1-9][0-9]*", declarations[0])):
            raise ValueError("rate_source_dictionary_multiplicity_declaration_invalid")
        species.append({"label": label, "adjacency_list": "\n".join(lines[1:]) + "\n",
                        "multiplicity_declaration": int(declarations[0].split()[1]) if declarations else None,
                        "electronic_state_inferred_from_connectivity": False})
    return {"artifact": artifact, "parsed": {"species": species}}


def _chemkin_annotations(path):
    text, artifact = _read(path)
    reactions, thermo, pending = [], {}, []
    in_reactions = in_thermo = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.upper().startswith("THERM"):
            in_thermo, in_reactions, pending = True, False, []
            continue
        if stripped.upper().startswith("REACTIONS"):
            in_reactions, in_thermo, pending = True, False, []
            continue
        if stripped.upper() == "END":
            in_reactions = in_thermo = False
            pending = []
            continue
        if stripped.startswith("!"):
            pending.append(stripped[1:].strip())
            continue
        if not stripped:
            continue
        if in_thermo and len(line) >= 80 and line[79:80] == "1":
            identifier = line[:18].split()[0]
            if identifier in thermo:
                raise ValueError("rate_source_chemkin_thermo_duplicate")
            thermo[identifier] = "\n".join(pending)
            pending = []
        elif in_reactions and ("=>" in stripped or "=" in stripped.split()[0]):
            equation = stripped.split()[0]
            pieces = re.split(r"(<=>|=>|=)", equation)
            if len(pieces) != 3:
                raise ValueError("rate_source_chemkin_equation_unsupported")
            source_library = [entry.partition(":")[2].strip() for entry in pending if entry.startswith("Library reaction:")]
            family = [entry.partition(":")[2].strip() for entry in pending if entry.startswith("Template reaction:")]
            indices = [entry for entry in pending if entry.startswith("Reaction index:")]
            expected_index = len(reactions) + 1
            if (len(indices) != 1 or not re.fullmatch(
                    r"Reaction index: Chemkin #%d; RMG #[0-9]+" % expected_index, indices[0])):
                raise ValueError("rate_source_chemkin_index_annotation_invalid_or_out_of_order")
            if len(source_library) > 1 or len(family) > 1 or (source_library and family):
                raise ValueError("rate_source_chemkin_source_ambiguous")
            comment = "\n".join(entry for entry in pending if not entry.startswith(
                ("Reaction index:", "Library reaction:", "Template reaction:", "Flux pairs:")))
            reactions.append({"reaction_index": len(reactions), "reactants": pieces[0].split("+"),
                              "products": pieces[2].split("+"), "reversible": pieces[1] != "=>",
                              "source_library": source_library[0] if source_library else None,
                              "family": family[0] if family else None, "kinetics_comment": comment})
            pending = []
    if not reactions or len(reactions) > MAX_MODEL_REACTIONS:
        raise ValueError("rate_source_chemkin_reaction_inventory_outside_policy")
    return reactions, thermo, artifact


def _safe_child(database, *parts):
    root = Path(database).resolve(strict=True)
    if not root.is_dir():
        raise ValueError("rate_source_database_directory_invalid")
    for part in parts:
        if (not isinstance(part, str) or not part or part in {".", ".."}
                or "/" in part or "\\" in part or "\x00" in part):
            raise ValueError("rate_source_database_path_component_unsafe")
    path = root.joinpath(*parts).resolve(strict=True)
    if root not in path.parents or not path.is_file():
        raise ValueError("rate_source_database_path_outside_root_or_not_file")
    return path


def _document(database, family, filename, labels=None, indices=None, training=False):
    parts = ["kinetics", "families", family]
    if training:
        parts.append("training")
    parts.append(filename)
    result = parse_database_document(_safe_child(database, *parts), labels, indices)
    result["role"] = ("training_reactions" if training else
                      "family_rules" if filename == "rules.py" else "family_groups")
    return result


def _family_ancestry(record, database):
    family, comment = record["family"], record["kinetics_comment"]
    documents, training, rules, reasons = [], [], [], []
    matched = list(re.finditer(r"^Matched reaction\s+(\d+)\s+(.+?)\s+in\s+([^\s]+?)/training$", comment, re.M))
    nodes = re.findall(r"^Estimated from node (.+?) in family ([^\s]+)\.?$", comment, re.M)
    rule_labels = re.findall(r"(?:matched rate rule|for rate rule)\s*\[([^\]\n]+)\]", comment)
    if len(matched) > 1 or len(nodes) > 1 or len(set(rule_labels)) > 1:
        raise ValueError("rate_source_annotation_ancestry_ambiguous")
    labels, converted_labels = set(rule_labels), set()
    if nodes:
        node, declared_family = nodes[0]
        if declared_family.rstrip(".") != family:
            raise ValueError("rate_source_annotation_family_mismatch")
        labels.add(node)
    if matched:
        match = matched[0]
        if match.group(3) != family:
            raise ValueError("rate_source_annotation_training_family_mismatch")
        document = _document(database, family, "reactions.py", indices={int(match.group(1))}, training=True)
        documents.append(document)
        training = document["parsed"]["entries"]
        if len(training) != 1 or training[0]["label"] != match.group(2):
            raise ValueError("rate_source_matched_training_index_or_label_mismatch")
        converted_labels.update(re.findall(r"Converted to training reaction from rate rule:\s*([^\n]+)",
                                           training[0].get("longDesc", "")))
        labels.update(converted_labels)
        training_labels = re.split(r"\s*(?:<=>|=>|=)\s*", training[0]["label"])
        if len(training_labels) != 2 or any("+" in item for item in training_labels):
            reasons.append("training_dictionary_multispecies_label_outside_initial_policy")
        else:
            dictionary = parse_species_dictionary(_safe_child(database, "kinetics", "families", family,
                                                             "training", "dictionary.txt"), set(training_labels))
            dictionary["role"] = "training_dictionary"
            documents.append(dictionary)
            if {entry["label"] for entry in dictionary["parsed"]["species"]} != set(training_labels):
                reasons.append("training_dictionary_referenced_species_missing")
    groups = _document(database, family, "groups.py", labels=labels)
    rule_document = _document(database, family, "rules.py", labels=labels)
    documents.extend([groups, rule_document])
    rules = rule_document["parsed"]["entries"]
    for label in sorted(converted_labels):
        if not any(entry["label"] == label for entry in rules):
            reasons.append("converted_rule_static_entry_missing: %s" % label)
    if nodes and (len(rules) != 1 or rules[0]["label"] != nodes[0][0]):
        reasons.append("estimated_node_rule_record_missing_or_ambiguous")
    if not matched and any(re.search(r"rule fitted to\s+[0-9]+\s+training reactions", entry.get("longDesc", ""), re.I)
                           for entry in rules):
        # The fitted count / statistical annotation does not identify the
        # contributors, nor establish their electronic-state applicability.
        reasons.append("fitted_rule_training_contributors_not_identified")
    if not matched and not nodes and not rule_labels:
        reasons.append("kinetics_annotation_ancestry_not_recognized")
    if rule_labels and not matched and not rules:
        reasons.append("annotated_rate_rule_record_missing")
    return documents, training, rules, reasons


def build_rate_source_snapshot(input_bindings):
    """Pure application-side reconstruction; no RMG or native database loader."""
    bindings = json.loads(json.dumps(input_bindings, allow_nan=False))
    for key in ("temperature_K", "pressure_bar"):
        value = bindings.get("condition", {}).get(key)
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or value <= 0.0:
            raise ValueError("rate_source_condition_positive_finite_numbers_required")
    exports = bindings["model_exports"]
    for record in exports.values():
        _reopen(record)
    reactions, thermo, _ = _chemkin_annotations(exports["chemkin"]["path"])
    native = bindings["native_annotations"]
    if len(native["reactions"]) != len(reactions):
        raise ValueError("rate_source_native_chemkin_reaction_inventory_mismatch")
    state_records = native["species"]
    if not 1 <= len(state_records) <= MAX_MODEL_SPECIES:
        raise ValueError("rate_source_native_species_inventory_outside_policy")
    ids = [record["chemkin_identifier"] for record in state_records]
    if len(set(ids)) != len(ids):
        raise ValueError("rate_source_native_species_identifier_duplicate")
    dictionary = parse_species_dictionary(exports["dictionary"]["path"], set(ids))
    by_id = {record["label"]: record for record in dictionary["parsed"]["species"]}
    if set(by_id) != set(ids):
        raise ValueError("rate_source_native_dictionary_species_inventory_mismatch")
    species = []
    for item in state_records:
        identifier, multiplicity = item["chemkin_identifier"], item["multiplicity"]
        if isinstance(multiplicity, bool) or not isinstance(multiplicity, int) or multiplicity < 1:
            raise ValueError("rate_source_native_species_multiplicity_invalid")
        declared = by_id[identifier]["multiplicity_declaration"]
        if declared is not None and declared != multiplicity:
            raise ValueError("rate_source_native_dictionary_multiplicity_mismatch")
        source_comment = thermo.get(identifier)
        if source_comment is None or source_comment != item["thermo_comment"]:
            raise ValueError("rate_source_native_chemkin_thermo_annotation_mismatch")
        source_kind = ("library" if source_comment.startswith("Thermo library:") else
                       "group_additivity" if source_comment.startswith("Thermo group additivity estimation:") else "unknown")
        species.append(dict(item, source_kind=source_kind, source_dictionary=by_id[identifier],
                            electronic_state_inferred_from_thermo_source=False,
                            thermo_applicability_verified=False))
    database = bindings.get("database_directory")
    database_reasons = []
    if not isinstance(database, str) or not Path(database).is_absolute() or not Path(database).is_dir():
        database_reasons.append("native_database_directory_unavailable")
    records, artifacts = [], list(exports.values())
    for retained, native_record in zip(reactions, native["reactions"]):
        for key in ("reaction_index", "reactants", "products", "reversible", "source_library", "family", "kinetics_comment"):
            if retained[key] != native_record[key]:
                raise ValueError("rate_source_native_chemkin_reaction_annotation_mismatch_%s" % key)
        source_kind = "library" if retained["source_library"] else "family_estimate" if retained["family"] else "unknown"
        record = dict(native_record, source_kind=source_kind, source_documents=[], training_entries=[],
                      rule_entries=[], unresolved_reasons=list(database_reasons))
        if retained["family"] and not database_reasons:
            try:
                documents, training, rules, reasons = _family_ancestry(retained, database)
                record.update(source_documents=documents, training_entries=training, rule_entries=rules)
                record["unresolved_reasons"].extend(reasons)
            except (OSError, ValueError, KeyError, TypeError) as error:
                reason = str(error) if isinstance(error, ValueError) else type(error).__name__
                record["unresolved_reasons"].append("family_source_extraction_unresolved: %s" % reason)
        elif source_kind == "library":
            # STORCA's generated external libraries have their own manifest /
            # identity ancestry.  Do not guess a same-named installed library.
            record["unresolved_reasons"].append("external_library_ancestry_requires_owning_manifest")
        elif source_kind == "unknown":
            record["unresolved_reasons"].append("retained_rate_source_annotation_unknown")
        record["ancestry_status"] = "unresolved" if record["unresolved_reasons"] else "source_records_extracted"
        record.update(physical_rate_applicability_verified=False, independent_experiment_verified=False,
                      electronic_state_rate_assignment_verified=False)
        artifacts.extend(document["artifact"] for document in record["source_documents"])
        records.append(record)
    artifacts = list({item["path"]: item for item in artifacts}.values())
    for record in artifacts:
        _reopen(record)
    result = {"schema_version": 1, "kind": "native_retained_rate_source_snapshot", "policy_id": POLICY_ID,
              "status": "completed" if all(record["ancestry_status"] == "source_records_extracted" for record in records) else "unresolved",
              "condition": bindings["condition"], "condition_contract_id": bindings.get("condition_contract_id"),
              "database_directory": database, "species": species, "reactions": records,
              "source_artifacts": artifacts, "source_artifacts_unchanged": True, "input_bindings": bindings,
              "source_snapshot_does_not_verify_historical_database_version": True,
              "rate_values_reconstructed_from_database": False, "physical_rate_bounds_established": False,
              "uncertainty_calibrated": False, "pressure_applicability_verified": False,
              "terminal_robustness_eligible": False, "lifetime_claim_allowed": False,
              "conclusive_observable_allowed": False}
    result["scientific_hash"] = _hash(result)
    return result


def collect_rate_source_snapshot(payload, species, reactions, records):
    """Collect native annotations, then use the same pure source reconstruction."""
    exports = {}
    for name in ("chemkin", "dictionary", "transport"):
        if payload.get(name):
            exports[name] = _read(payload[name])[1]
    if "chemkin" not in exports or "dictionary" not in exports:
        raise ValueError("rate_source_model_exports_missing")
    if len(species) != len(records):
        raise ValueError("rate_source_native_state_record_count_mismatch")
    identifiers = {id(item): record["chemkin_identifier"] for item, record in zip(species, records)}
    native_species = []
    for item, record in zip(species, records):
        thermo = getattr(item, "thermo", None)
        native_species.append({"chemkin_identifier": record["chemkin_identifier"], "multiplicity": record["multiplicity"],
                               "thermo_comment": str(getattr(thermo, "comment", "") or ""),
                               "thermo_model_class": type(thermo).__name__ if thermo is not None else None})
    native_reactions = []
    for index, reaction in enumerate(reactions):
        kinetics = getattr(reaction, "kinetics", None)
        library = str(getattr(reaction, "library", "") or "") or None
        # RMG LibraryReaction.family aliases its library name; it is not a
        # Template reaction declaration in the owning Chemkin annotation.
        family = None if library else str(getattr(reaction, "family", "") or "") or None
        native_reactions.append({"reaction_index": index,
                                 "reactants": [identifiers[id(item)] for item in reaction.reactants],
                                 "products": [identifiers[id(item)] for item in reaction.products],
                                 "reversible": bool(reaction.reversible),
                                 "source_library": library,
                                 "family": family,
                                 "kinetics_comment": str(getattr(kinetics, "comment", "") or ""),
                                 "kinetics_model_class": type(kinetics).__name__ if kinetics is not None else None})
    try:
        from rmgpy import settings
        database = str(Path(settings["database.directory"]).resolve(strict=True))
    except (ImportError, OSError, KeyError, TypeError, ValueError):
        database = None
    bindings = {"model_exports": exports, "database_directory": database,
                "condition": {"temperature_K": payload["temperature_K"], "pressure_bar": payload["pressure_bar"]},
                "condition_contract_id": payload.get("condition_contract_id"),
                "native_annotations": {"species": native_species, "reactions": native_reactions}}
    return build_rate_source_snapshot(bindings)


def validate_rate_source_snapshot(snapshot):
    """Reopen every file and recompute ancestry; no native loader is required."""
    if (not isinstance(snapshot, dict) or snapshot.get("schema_version") != 1
            or snapshot.get("kind") != "native_retained_rate_source_snapshot"
            or snapshot.get("policy_id") != POLICY_ID):
        raise ValueError("rate_source_snapshot_schema_or_policy_invalid")
    original = dict(snapshot)
    digest = original.pop("scientific_hash", None)
    if digest != _hash(original):
        raise ValueError("rate_source_snapshot_scientific_hash_mismatch")
    for artifact in snapshot.get("source_artifacts", []):
        _reopen(artifact)
    rebuilt = build_rate_source_snapshot(snapshot["input_bindings"])
    if rebuilt != snapshot:
        raise ValueError("rate_source_snapshot_reconstruction_mismatch")
    return rebuilt
